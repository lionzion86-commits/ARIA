/* ==================================================================
   THE SEARCH WATCH LIST — against the real catalogue, the way
   search.html runs it.

   2026-10-07: six of nine watch queries were dead pages on production.
   Every search on the site lands on search.html, and search.html ran
   its own exact-word matcher instead of the site's engine. It now runs
   search-engine.js (index.html's engine, generated by
   scripts/build-search-engine.mjs). This suite loads that file and the
   committed catalogues the way the page does, and asks the questions
   shoppers asked.

   RUNNING IT
     node scripts/test/search-watch-tests.mjs
   ================================================================== */
import assert from "node:assert/strict";
import { readFileSync, existsSync } from "node:fs";
import vm from "node:vm";
import { buildSearchEngineSource } from "../build-search-engine.mjs";

const ROOT = new URL("../../", import.meta.url).pathname;
let passed = 0;
const failures = [];
function check(name, fn) {
  try { fn(); passed++; console.log("    ok   " + name); }
  catch (e) { failures.push(`${name}\n         ${e.message}`); }
}

/* ------------------------------------------------------------------
   NO DRIFT. search-engine.js is generated; a change to search in
   index.html that was not regenerated would leave the site's main
   search page running the old engine.
   ------------------------------------------------------------------ */
const engineSrc = readFileSync(ROOT + "search-engine.js", "utf8");
check("search-engine.js is the engine index.html has today", () => {
  assert.equal(engineSrc, buildSearchEngineSource(),
    "search-engine.js is stale — run: node scripts/build-search-engine.mjs");
});

check("search.html runs the engine, not its own matcher", () => {
  const page = readFileSync(ROOT + "search.html", "utf8");
  assert.match(page, /<script src="search-engine\.js"><\/script>/, "search.html does not load the engine");
  assert.match(page, /S\.rankCatalogMatches\(PRODUCTS,/, "search.html does not rank with the engine");
  assert.match(page, /S\.soundCorrectQuery\(/, "search.html does not correct typos");
  assert.match(page, /suggestSearchQuery\(/, "a zero-result search has no \"¿Quisiste decir?\"");
  assert.match(page, /var SALE_FEED = "\/ofertas-feed\.json";/, "sale-only deals are not searchable");
});

/* ------------------------------------------------------------------
   THE CATALOGUE, LOADED THE WAY search.html LOADS IT.
   ------------------------------------------------------------------ */
const sandbox = { window: {}, console };
vm.createContext(sandbox);
vm.runInContext(engineSrc, sandbox, { filename: "search-engine.js" });
const S = sandbox.window.AriaSearch;

const page = readFileSync(ROOT + "search.html", "utf8");
const files = JSON.parse("[" + /var CATALOG_FILES = \[([\s\S]*?)\];/.exec(page)[1] + "]");
const products = [];
const seen = new Set();
const norm = (it, retailer, department, finalPrice) => {
  const name = it && (it.name || it.title);
  const price = Number(it && it.price);
  if (!name || !(price > 0)) return null;
  const orig = Number(it.originalPrice || it.wasPrice || it.listPrice);
  return { name: String(name), title: String(name), brand: String(it.brand || ""), price,
    originalPrice: orig > price ? orig : null, onSale: it.onSale === true,
    departments: department ? [department] : [], finalPrice, retailer: String(it.retailer || retailer || "") };
};
for (const f of files) {
  if (!existsSync(ROOT + f.slice(1))) continue;
  const data = JSON.parse(readFileSync(ROOT + f.slice(1), "utf8"));
  for (const [rkey, r] of Object.entries((data && data.retailers) || {})) {
    for (const section of ["departments", "brands"]) {
      for (const [skey, bucket] of Object.entries((r && r[section]) || {})) {
        const arr = Array.isArray(bucket) ? bucket : (bucket && bucket.items) || [];
        for (const it of arr) {
          const n = norm(it, rkey, section === "departments" ? skey : "", false);
          if (!n) continue;
          const k = (n.retailer + "|" + (it.url || it.link || n.name)).toLowerCase();
          if (seen.has(k)) continue;
          seen.add(k);
          products.push(n);
        }
      }
    }
  }
}
const have = new Set(products.map(p => (p.retailer + "|" + p.name).toLowerCase()));
for (const it of JSON.parse(readFileSync(ROOT + "ofertas-feed.json", "utf8")).items || []) {
  const n = norm(it, it && it.retailer, "", true);
  if (!n) continue;
  const k = (n.retailer + "|" + n.name).toLowerCase();
  if (have.has(k)) continue;
  have.add(k);
  products.push(n);
}
S.buildSearchWordIndex(products);
const retailers = [...new Set(products.map(p => p.retailer))].map(k => ({ key: k, label: k }));

/* Exactly search.html's engineSearch(). */
function search(query) {
  const t1 = S.translateQuery(query);
  const fixed = S.soundCorrectQuery(t1.query, products._windex);
  const t = fixed.changed ? S.translateQuery(fixed.query) : t1;
  const res = S.rankCatalogMatches(products, t.query, { limit: 60, retailers });
  const hits = (res && res.items) || [];
  return { hits, corrected: fixed.changed ? fixed.query : null,
    suggestion: hits.length ? null : S.suggestSearchQuery(t.query, products._windex) };
}
const top = (r, n) => r.hits.slice(0, n);
const titles = (r, n) => top(r, n).map(h => h.title).join(" | ");

check("the catalogue loaded", () => {
  assert.ok(products.length > 100000, `only ${products.length} products loaded`);
});

/* ------------------------------------------------------------------
   THE NINE WATCH QUERIES (2026-10-07).
   ------------------------------------------------------------------ */
check('"chort" is shorts, not Schott', () => {
  const r = search("chort");
  assert.equal(r.corrected, "short", "the typo was not corrected to short");
  assert.ok(r.hits.length, "dead page");
  assert.ok(top(r, 5).every(h => /\bshorts?\b/i.test(h.title)), "the top five are not shorts: " + titles(r, 5));
  assert.ok(!top(r, 10).some(h => /schott/i.test(h.brand)), "Schott hijacked the search again");
});

check('"swetshert" is sweatshirts', () => {
  const r = search("swetshert");
  assert.equal(r.corrected, "sweatshirt");
  assert.ok(top(r, 5).every(h => /sweatshirt|hoodie|hooded|pullover/i.test(h.title)), titles(r, 5));
  assert.ok(!top(r, 10).some(h => /sweetheart/i.test(h.title)), "it matched sweethearts again");
});

check('"hudi" is hoodies, not the brand Huddy', () => {
  const r = search("hudi");
  assert.equal(r.corrected, "hoodie");
  assert.ok(top(r, 5).every(h => /hoodie|hooded|sweatshirt/i.test(h.title)), titles(r, 5));
  assert.ok(!top(r, 10).some(h => /huddy/i.test(h.brand)), "Huddy hijacked the search again");
});

check('"youg la" is YoungLA', () => {
  const r = search("youg la");
  assert.ok(r.hits.length >= 10, "dead page");
  assert.ok(top(r, 10).every(h => /youngla/i.test(h.brand.replace(/\s/g, ""))), titles(r, 10));
});

check('"victoria secret sales" is Victoria\'s Secret on sale', () => {
  const r = search("victoria secret sales");
  assert.ok(r.hits.length >= 10, "dead page — the flagship brand must work");
  assert.ok(top(r, 10).every(h => /victoria/i.test(h.brand)), "another brand leaked in: " + titles(r, 10));
  const onSale = top(r, 10).filter(h => Number(h.originalPrice) > Number(h.price) || h.onSale).length;
  assert.ok(onSale >= 8, `sale intent did not lead with markdowns (${onSale}/10 discounted)`);
});

check('"zapatilla" is sneakers — never a doll', () => {
  const r = search("zapatilla");
  assert.ok(r.hits.length >= 10, "dead page");
  const shoe = /\b(?:shoes?|sneakers?|trainers?|boots?|sandals?|slides?|clogs?|cleats?|runners?|slip-ons?|loafers?)\b/i;
  const shoes = top(r, 10).filter(h => shoe.test(h.title) || h.retailer === "footlocker").length;
  assert.ok(shoes >= 8, `only ${shoes}/10 of the top results are footwear: ` + titles(r, 10));
  assert.ok(!top(r, 20).some(h => /barbie|\bdolls?\b|mu[nñ]eca|figurine/i.test(h.title)), "a toy answered a footwear search");
  /* Singular and plural are the same question. */
  assert.equal(titles(search("zapatillas"), 10), titles(r, 10), "zapatilla and zapatillas disagree");
});

check('the three that already passed still pass ("shor", "adidas", "ñike")', () => {
  assert.ok(search("shor").hits.length, '"shor" is a dead page');
  assert.ok(top(search("adidas"), 10).every(h => /adidas/i.test(h.brand)), '"adidas" leaked another brand');
  assert.ok(top(search("ñike"), 10).every(h => /nike/i.test(h.brand)), '"ñike" is not Nike');
});

/* ------------------------------------------------------------------
   WHAT CAME WITH IT.
   ------------------------------------------------------------------ */
check("the sound-alike layer does not swallow real brands or real words", () => {
  assert.ok(top(search("snikers"), 5).every(h => /shoe|sneaker/i.test(h.title)), '"snikers" is not sneakers');
  assert.ok(top(search("jeans"), 5).every(h => /jeans|pants|denim/i.test(h.title)), '"jeans" lost to a "Party Pants" brand');
  assert.ok(top(search("snickers"), 5).every(h => /snickers/i.test(h.title)), "the real brand Snickers stopped matching");
});

check("a sale-feed-only deal is found (Titan Pro MMA Glove)", () => {
  assert.equal(top(search("titan pro mma"), 1)[0]?.title, "Titan Pro MMA Glove");
});

check('a dead page offers "¿Quisiste decir?"', () => {
  const r = search("hudi qqqzx");
  if (!r.hits.length) assert.ok(r.suggestion && /hoodie/.test(r.suggestion), "no suggestion for an empty page");
  assert.equal(S.suggestSearchQuery("hudi", products._windex), "hoodie");
  assert.equal(S.suggestSearchQuery("qqqzxv", products._windex), null, "nonsense got a made-up suggestion");
});

const MIN_CHECKS = 13;
if (passed + failures.length < MIN_CHECKS) {
  console.log(`\n  SUITE INCOMPLETE: ${passed + failures.length} ran, expected ${MIN_CHECKS}.`);
  process.exit(1);
}
console.log(`\n  ${passed} passed, ${failures.length} failed\n`);
if (failures.length) { for (const f of failures) console.log("  FAIL  " + f); process.exit(1); }
