/* ============================================================
   SIBLING WEIGHT INFERENCE (#449 pricing, 2026-10-21)

   Danny's option-3 ruling on #443, signed off on #449 with Lucifer's
   conditions: a product UNDER $75 that no row recognises is weighed like
   its verified siblings -- the products of the same department and the
   same kind (the title's noun) that carry a real weight or a row weight
   -- instead of the 0.6 kg generic. The figure is the siblings' median
   x 1.10; with fewer than 5 siblings, the department's median x 1.10;
   with a department too thin for that, the whole catalogue's. Capped at
   2 kg, except a pinned type that states a real weight above it (dirt-
   bike tyres). A few hand-checked types are pinned outright (trading
   cards, jewellery, surf leashes...), and every inferred figure is held
   inside its type's plausible range, so none is physically absurd.

   The numbers are DATA, not code: scripts/report-weight-inference.mjs
   computes them from the catalogue and writes the same object twice,
   to ./inferred-weights-data.js (imported here, so the server resolver
   bundles it) and to assets/weight/inferred-weights.json (fetched once
   by the app bundle). Cluster level only: no per-product data.

   A cart line carries no department, so the department is the store's:
   data.stores maps a store to its main department, with per-type
   exceptions where that store's products of a kind live elsewhere
   (Walmart's balls are sporting goods, its puzzles toys). The card, the
   product page, checkout and orders-create all ask the same question
   (title, store, price) and get the same answer.

   Every answer is flagged `inferred` (source "inferred" in the resolver)
   and is an estimate like any row weight: it is labelled "peso
   estimado", never "confirmado". It is NOT a gap: Danny's 889 ruling --
   a truthful quote is information, not a wall -- so freightQuotable()
   does not hold it for costing more than the product.
   ============================================================ */
export const INFERENCE_UNDER_USD = CONSERVATIVE_PRICE_USD;

/* The title the type rules read: lower case, accents and curly quotes
   folded, exactly as the builder normalised it. */
export function inferenceTitle(title) {
  return String(title || "").toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[’']/g, "'");
}

let inferenceCompiled = null, inferenceCompiledFor = null;
function compileInference(data) {
  if (inferenceCompiledFor === data) return inferenceCompiled;
  inferenceCompiled = {
    types: (data.types || []).map(([k, src]) => [k, new RegExp(src)]),
    pins: (data.pins || []).map((p) => ({ ...p, re: p.match ? new RegExp(p.match) : null, steps: (p.steps || []).map(([src, kg]) => [new RegExp(src), kg]) })),
  };
  inferenceCompiledFor = data;
  return inferenceCompiled;
}

/**
 * The inferred shipping weight for a product no row recognised, or null
 * (no price, $75 or more, or no data). hints: { retailer, priceUsd }.
 * Returns { kg, basis, key, dept, type, capped } where basis is
 * "pinned" | "sibling" | "dept-median" | "catalog-median".
 */
let ACTIVE_INFERRED_WEIGHTS = INFERRED_WEIGHTS;
/* The builder re-resolves the catalogue with the data it just wrote. */
export function useInferredWeights(data) { ACTIVE_INFERRED_WEIGHTS = data; }
export function inferredWeightKg(title, hints = {}, data = ACTIVE_INFERRED_WEIGHTS) {
  if (!data || !Array.isArray(data.types)) return null;
  const h = hints || {};
  const price = Number(h.priceUsd);
  if (!(price > 0) || !(price < (data.underUsd || INFERENCE_UNDER_USD))) return null;
  const c = compileInference(data);
  const t = inferenceTitle(title);
  let type = "other";
  for (const [k, re] of c.types) if (re.test(t)) { type = k; break; }
  const store = (data.stores || {})[String(h.retailer || "").toLowerCase()] || null;
  const dept = store ? ((store[1] && store[1][type]) || store[0]) : null;
  for (const pin of c.pins) {
    if (pin.dept && pin.dept !== dept) continue;
    if (pin.types ? !pin.types.includes(type) : !(pin.re && pin.re.test(t))) continue;
    let kg = pin.kg;
    for (const [re, k] of pin.steps) if (re.test(t)) { kg = k; break; }
    return { kg, basis: "pinned", key: pin.key, dept, type, capped: false };
  }
  const cluster = dept && type !== "other" && data.clusters && data.clusters[dept] ? data.clusters[dept][type] : undefined;
  let kg, basis, key;
  if (cluster != null) { kg = cluster; basis = "sibling"; key = dept + "/" + type; }
  else if (dept && data.depts && data.depts[dept] != null) { kg = data.depts[dept]; basis = "dept-median"; key = dept; }
  else { kg = data.catalog; basis = "catalog-median"; key = "catálogo"; }
  /* The physical-sanity range of the type: a department median never
     prices a pair of earrings like a lamp. */
  const range = data.ranges && data.ranges[type];
  if (range) kg = Math.min(range[1], Math.max(range[0], kg));
  const cap = data.capKg || 2;
  const capped = kg > cap;
  return { kg: Math.round((capped ? cap : kg) * 100) / 100, basis, key, dept, type, capped };
}

/* An inferred figure sits inside the title's own sanity band when one
   claims it (a band is a harder fact than a median). It is moved INTO
   the band rather than flagged out of it: inference exists to give
   these products a truthful quote, not a new hold. */
export function clampToBand(title, kg) {
  const band = bandFor(title);
  let n = Number(kg);
  if (!band) return n;
  if (n < band.minKg) n = band.minKg;
  if (band.maxKg != null && n > band.maxKg) n = band.maxKg;
  return n;
}

/* MOMS PLACEHOLDER WEIGHTS (#449). The moms catalogue stamps a flat
   category default on products it could not weigh, marked estimated:
   4.0 kg (swaddles, a bath thermometer, a monitor), 12 kg ("Stroller
   Party" clips and seat liners) and 25 kg (crib SHEETS). Those are not
   weights; read as catalogue weights they poisoned the sibling pools and
   quoted a swaddle at 4 kg. On a line under $75, 4.0 is never a weight
   and 12 / 25 stay only on the stroller / crib they were stamped for; a
   $75+ line keeps the stamp as on main (a playard or a crib is heavier
   than the band top). Store-scoped to the baby stores, so no other
   catalogue's 4.0 is touched. Mirrored in the bundle. */
export const CATALOG_PLACEHOLDERS = [
  { kg: 4 },
  { kg: 12, keep: /\b(strollers?|car ?seats?|travel systems?|playards?|pack ?n ?play|high ?chairs?|bassinets?)\b/i, unless: STROLLER_ACCESSORY_RE },
  { kg: 25, keep: /\bcribs?\b/i, unless: /\b(sheets?|mattress(?:es)?)\b/i },
];
export function isCatalogPlaceholder(kg, retailer, title, hints = {}) {
  if (RETAILER_DEPARTMENT[String(retailer || "").toLowerCase()] !== "bebé") return false;
  const n = Number(kg);
  const t = String(title || "");
  const p = CATALOG_PLACEHOLDERS.find((x) => x.kg === n);
  if (!p) return false;
  /* Judged on cheap lines only (#449): under $75 a stamp is no weight and
     inference answers. At $75+ the stamp stands as on main -- dropping it
     there sends playards, high chairs and cribs to the 2 kg band top. */
  if (!isCheapLine(hints)) return false;
  if (!p.keep) return true;
  return !(p.keep.test(t) && !(p.unless && p.unless.test(t)));
}

/* hints.priceUsd (#449): the misfire guards below (cheapNot, NOT_BULKY_RE,
   rugs by area) read only lines UNDER $75 or with no price. A $449
   pantry cabinet that names its "organizers" keeps its row exactly as on
   main; a $14 cabinet spice rack does not take it. */
export function bulkyWeightKg(text, hints = {}) {
  const t = String(text || "");
  const cheap = isCheapLine(hints);
  // Toys first, at published weights: see LARGE_TOY_WEIGHTS_KG.
  const toy = largeToyWeightKg(t, hints);
  if (toy != null) return toy;
  const goal = goalWeightKg(t);
  if (goal != null) return goal;
  if (cheap) {
    const rug = rugWeightKg(t);
    if (rug != null) return rug;
  }
  const hit = BULKY_WEIGHT_ESTIMATES_KG.find((p) => p.match.test(t) && !(p.not && p.not.test(t))
    && !(cheap && p.cheapNot && p.cheapNot.test(t)) && !(p.cheapOnly && !cheap));
  if (!hit) return null;
  // Small goods that name a bulky thing (#449): see NOT_BULKY_RE.
  if (cheap && hit.kg >= 10 && notBulkyTitle(t)) return null;
  return withBuffer(hit.kg, "reasoned");
}

/** A line under $75, or one with no price: the #449 misfire guards apply. */
export function isCheapLine(hints) {
  return !(Number((hints || {}).priceUsd) >= CONSERVATIVE_PRICE_USD);
}

/* RUGS BY SIZE (#449, 2026-10-21). One 16 kg row priced every rug, so a
   $15 2'x3' bath rug quoted 21.6 kg with the buffer. A rug's weight is
   its area: ~0.12 kg per square foot for the low-pile and washable rugs
   these stores sell (an 8'x10' runs 8-13 kg), reasoned buffer on top.
   A title with no size keeps the 16 kg row. Mirrored in the app bundle. */
export const RUG_KG_PER_SQFT = 0.12;
export function rugWeightKg(title) {
  const t = String(title || "");
  if (!/\b(rug|carpet|area rug)\b/i.test(t)) return null;
  /* No usable size: a cheap rug is a small one (a mat 2 kg, else 4 kg,
     buffer on top), never the 16 kg area-rug row. */
  const unsized = () => withBuffer(/\b(mats?|doormats?)\b/i.test(t) ? 2 : 4, "reasoned");
  const m = /(\d+(?:\.\d+)?)\s*('|′|ft|feet|"|″|in(?:ch(?:es)?)?)?\s*[x×*]\s*(\d+(?:\.\d+)?)\s*('|′|ft\b|feet\b|"|″|in(?:ch(?:es)?)?\b)?/i.exec(t);
  if (!m) return unsized();
  const a = parseFloat(m[1]), b = parseFloat(m[3]);
  const unit = String(m[2] || "") + String(m[4] || "");
  const inches = /"|″|in/i.test(unit) || (!/'|′|ft|feet/i.test(unit) && a > 15 && b > 15);
  if (!inches && !/'|′|ft|feet/i.test(unit) && (a > 15 || b > 15)) return unsized();
  const sqft = inches ? (a * b) / 144 : a * b;
  if (!(sqft > 0)) return unsized();
  const kg = withBuffer(Math.min(30, Math.max(0.5, sqft * RUG_KG_PER_SQFT)), "reasoned");
  /* A rug that states 4 ft or more meets the oversized band's 4 kg floor
     (see WEIGHT_SANITY_BOUNDS): quoted at it, never held below it. */
  const longestFt = inches ? Math.max(a, b) / 12 : Math.max(a, b);
  return longestFt >= 4 ? Math.max(kg, 4) : kg;
}

/* ============================================================
   SANITY BOUNDS (2026-09-19) — the tripwire under every estimate.

   The tables above only help for a title they recognise. The soccer goal
   showed what happens when one slips past: it published at 1.08 kg, the
   generic fallback, and we would have honoured $14 of freight on a
   pallet. These bounds are deliberately BROADER than the estimate table —
   they match the kind of thing being sold, not a specific product — so an
   unrecognised title still cannot publish an implausible weight.

   BANDS, NOT JUST FLOORS (2026-09-20). A floor only catches an estimate
   that is too LIGHT. The other half of the bleed is an estimate that is
   too HEAVY: a men's leather sneaker answered at 1.94 kg against a
   plausible 0.8-1.6, which is half a kilo of air and roughly S/ 22 of
   phantom freight on a single pair. Every bound now carries a maxKg as
   well, and an estimate outside its band FAILS CLOSED — see weightSanity
   and the `needsReview` flag it raises. Nothing renders a freight quote
   from a weight we do not believe; the item goes to manual review, and
   the customer is told the freight is being confirmed rather than shown
   a number that is wrong in either direction.

   A weight outside its band is NOT silently corrected and forgotten.
   Under the floor, the floor is applied for any internal use (we never
   under-quote ourselves); over the ceiling the original figure is kept,
   because clamping DOWN would turn a display problem into a margin loss
   the day some path ignores the flag. Either way the item is flagged and
   the refresh scripts print it.

   BANDS APPLY TO ESTIMATES, NOT TO FACTS. A weight the retailer
   published is a measurement and is never band-checked — see
   resolveItemWeight().
   ============================================================ */
