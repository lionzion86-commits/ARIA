#!/usr/bin/env node
/* ============================================================
   parts-glossary.js — AUTO PART NAMES, BOTH WAYS, FOR THE STANDALONE PAGES.

   WHY (2026-10-13, issue #386 F10 / BASE-5). Typed Aria Auto search on
   auto.html answered "brake pads" (2020 Corolla) with "Sin resultados"
   while "pastillas de freno" returned 51 parts: the parts cache is keyed
   in Spanish, and only the voice path (index.html) knew to translate
   English part names back with translatePartQueryToEs. auto.html now
   runs that same function -- lifted out of index.html by name with
   scripts/lib/page-lift.mjs, nothing re-implemented. index.html's copy
   is itself generated from scripts/lib/es-en-parts-glossary.json, so
   there is still one glossary.

   REGENERATE after the glossary or those functions change:
     node scripts/build-parts-glossary-js.mjs
   scripts/test/assistant-turn-tests.mjs fails if this file has drifted.
   ============================================================ */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { extractDeclarations, pageHtml } from "./lib/page-lift.mjs";

const ROOT = fileURLToPath(new URL("../", import.meta.url));

export const PARTS_GLOSSARY_DECLARATIONS = [
  "AUTO_PART_TERMS_ES_EN", "deaccent", "translatePartQuery", "AUTO_PART_TERMS_EN_ES", "translatePartQueryToEs",
];

export function buildPartsGlossarySource() {
  /* The page as written: index.html with its JS bundle inlined. */
  const html = pageHtml(ROOT);
  return `/* GENERATED by scripts/build-parts-glossary-js.mjs from index.html -- do not edit.
   Regenerate: node scripts/build-parts-glossary-js.mjs */
(function (root) {
'use strict';
${extractDeclarations(html, PARTS_GLOSSARY_DECLARATIONS)}
root.AriaPartsGlossary = { toEnglish: translatePartQuery, toSpanish: translatePartQueryToEs };
})(typeof window !== 'undefined' ? window : globalThis);
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const src = buildPartsGlossarySource();
  writeFileSync(ROOT + "parts-glossary.js", src);
  console.log(`parts-glossary.js: ${(src.length / 1024).toFixed(1)}KB`);
}
