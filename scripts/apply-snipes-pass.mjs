#!/usr/bin/env node
/* ============================================================
   THE SNIPES PDP PASS INTO snipes-catalog.json (#443; Lucifer's drop
   snipes-pass-2026-10-28 @ f7139425, branch snipes-pass-2026-10-28,
   data-drops/snipes-pass-2026-10-28/dataset.json -- the drop, not the
   site, so it is not on main). Rules: applySnipesPass in
   scripts/lib/store-pull-normalize.js.

     node scripts/apply-snipes-pass.mjs --pass <dataset.json>

   Runs on the committed catalogue (after build-pull-catalogs, the weight
   estimates and the description memory). Rewrites the shown-not-sold list
   (SNIPES' entries only; every other store's stay) and writes
   reports/snipes-pass-2026-10-28.json. Then rebuild the slices
   (build-store-slices, ofertas, search, pdp, price index).
   ============================================================ */
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { applySnipesPass } from "./lib/store-pull-normalize.js";
import { sizesPendingKey } from "./lib/sizes-pending.js";
import { SIZES_PENDING } from "./lib/sizes-pending-data.js";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const arg = (k) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : null; };
const PASS = arg("--pass");
if (!PASS) { console.error("usage: node scripts/apply-snipes-pass.mjs --pass <snipes-pass-2026-10-28/dataset.json>"); process.exit(2); }

const file = join(ROOT, "snipes-catalog.json");
const cat = JSON.parse(readFileSync(file, "utf8"));
if (/2026-10-28 PDP pass/.test(cat.source || "")) { console.error("snipes-catalog.json already carries the 2026-10-28 pass"); process.exit(1); }
const deps = cat.retailers.snipes.departments;
const count = () => Object.values(deps).reduce((n, d) => n + d.items.length, 0);
const before = count();
const report = applySnipesPass(deps, JSON.parse(readFileSync(resolve(PASS), "utf8")));
const kept = count();
cat.declaredProductCount = kept;
cat.source += "; sizes and compare-at prices from the 2026-10-28 PDP pass (snipes-pass-2026-10-28)";
writeFileSync(file, JSON.stringify(cat));

const pending = new Set(SIZES_PENDING.filter((k) => !k.startsWith("snipes::")));
for (const d of Object.values(deps)) for (const it of d.items) if (it.sizesPending) pending.add(sizesPendingKey("snipes", it.name));
const list = [...pending].sort();
writeFileSync(join(ROOT, "scripts/lib/sizes-pending-data.js"),
  "/* GENERATED by scripts/build-pull-catalogs.mjs -- the items shown but not sold until their sizes are confirmed\n" +
  "   (scripts/lib/sizes-pending.js). Do not edit by hand. */\n" +
  "export const SIZES_PENDING = " + JSON.stringify(list) + ";\n");
writeFileSync(join(ROOT, "assets/data/sizes-pending.json"), JSON.stringify(list));
const out = { before, kept, ...report, snipesPending: list.filter((k) => k.startsWith("snipes::")).length };
writeFileSync(join(ROOT, "reports/snipes-pass-2026-10-28.json"), JSON.stringify(out, null, 1) + "\n");
console.log(JSON.stringify(out, null, 1));
