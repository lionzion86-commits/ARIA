#!/usr/bin/env node
/* ============================================================
   THE SNIPES PDP PASS INTO snipes-catalog.json (#443, drop
   snipes-pass-2026-10-28 @ f7139425): sizes and compare-at prices off
   each product page. The rules are applySnipesPass in
   scripts/lib/store-pull-normalize.js.

     node scripts/apply-snipes-pass.mjs --pass <snipes-pass dataset.json>

   Runs on the committed catalogue (after build-pull-catalogs, the weight
   estimates and the description memory), rewrites the shown-not-sold
   list for both pull stores, and writes reports/snipes-pass-2026-10-28.json.
   ============================================================ */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { applySnipesPass } from "./lib/store-pull-normalize.js";
import { sizesPendingKey } from "./lib/sizes-pending.js";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const arg = (k) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : null; };
const PASS = arg("--pass");
if (!PASS) { console.error("usage: node scripts/apply-snipes-pass.mjs --pass <snipes-pass-2026-10-28/dataset.json>"); process.exit(2); }

const file = join(ROOT, "snipes-catalog.json");
const cat = JSON.parse(readFileSync(file, "utf8"));
const deps = cat.retailers.snipes.departments;
const before = Object.values(deps).reduce((n, d) => n + d.items.length, 0);
const report = applySnipesPass(deps, JSON.parse(readFileSync(PASS, "utf8")));
const kept = Object.values(deps).reduce((n, d) => n + d.items.length, 0);
cat.declaredProductCount = kept;
cat.source += "; sizes and compare-at prices from the 2026-10-28 PDP pass (snipes-pass-2026-10-28)";
writeFileSync(file, JSON.stringify(cat));

/* Shown, not sold: what is still sizeless, both pull stores. */
const pending = new Set();
for (const key of ["snipes", "carolinaherrera"]) {
  const c = JSON.parse(readFileSync(join(ROOT, key + "-catalog.json"), "utf8"));
  for (const d of Object.values(c.retailers[key].departments)) for (const it of d.items) if (it.sizesPending) pending.add(sizesPendingKey(key, it.name));
}
writeFileSync(join(ROOT, "scripts/lib/sizes-pending-data.js"),
  "/* GENERATED by scripts/build-pull-catalogs.mjs and scripts/apply-snipes-pass.mjs -- the items shown but not sold until their sizes are confirmed\n" +
  "   (scripts/lib/sizes-pending.js). Do not edit by hand. */\n" +
  "export const SIZES_PENDING = " + JSON.stringify([...pending].sort()) + ";\n");
writeFileSync(join(ROOT, "assets/data/sizes-pending.json"), JSON.stringify([...pending].sort()));
const out = { before, kept, ...report, pendingNames: pending.size };
writeFileSync(join(ROOT, "reports/snipes-pass-2026-10-28.json"), JSON.stringify(out, null, 1));
console.log(JSON.stringify(out, null, 1));
