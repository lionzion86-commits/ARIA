#!/usr/bin/env node
/* ============================================================
   calzedonia-catalog.json + intimissimi-catalog.json FROM THE
   2026-10-29 DROP (#443 c.6512405832).

   The drop is on branch data/calzedonia-intimissimi-2026-10-29, folder
   data-drops/2026-10-29-calzedonia-intimissimi/. Point --src at it:

     node scripts/build-calzedonia-intimissimi-catalogs.mjs --src <drop dir>

   The rules are scripts/lib/calzedonia-intimissimi.js. It writes both
   catalogues, adds Calzedonia's size-pending items to the list the
   order door reads (scripts/lib/sizes-pending-data.js, keeping every
   other store's entries), and reports/calzedonia-intimissimi-2026-10-29.json.
   ============================================================ */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { STORES, normalizeStore } from "./lib/calzedonia-intimissimi.js";
import { sizesPendingKey } from "./lib/sizes-pending.js";
import { SIZES_PENDING } from "./lib/sizes-pending-data.js";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const arg = (k) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : null; };
const SRC = arg("--src");
if (!SRC) { console.error("usage: node scripts/build-calzedonia-intimissimi-catalogs.mjs --src <2026-10-29-calzedonia-intimissimi dir>"); process.exit(2); }

const generatedAt = new Date().toISOString();
const report = { generatedAt, stores: {} };
const pending = new Set(SIZES_PENDING.filter((k) => !Object.keys(STORES).some((s) => k.startsWith(s + "::"))));
for (const [key, cfg] of Object.entries(STORES)) {
  const rows = JSON.parse(readFileSync(join(SRC, key + ".json"), "utf8"));
  const { departments, held } = normalizeStore(key, rows);
  const all = Object.values(departments).flatMap((d) => d.items);
  writeFileSync(join(ROOT, key + "-catalog.json"), JSON.stringify({ generatedAt,
    source: `${cfg.label} US storefront (direct HTTP: category grids + product-page JSON-LD), pulled 2026-10-29 (#443 c.6512405832)`,
    declaredProductCount: all.length, retailers: { [key]: { label: cfg.label, departments } } }));
  for (const it of all) if (it.sizesPending) pending.add(sizesPendingKey(key, it.name));
  report.stores[key] = { rawProducts: rows.length, kept: all.length, held,
    byAisle: Object.fromEntries(Object.entries(departments).map(([k, d]) => [k, d.items.length])),
    sizesPending: all.filter((i) => i.sizesPending).length, withSpanish: all.filter((i) => i.description).length,
    weightEstimated: all.filter((i) => i.weightEstimated).length, onSale: 0 };
  console.log(`${key}: ${all.length} kept of ${rows.length}`, report.stores[key].byAisle, held);
}
const list = [...pending].sort();
writeFileSync(join(ROOT, "scripts/lib/sizes-pending-data.js"),
  "/* GENERATED by scripts/build-pull-catalogs.mjs -- the items shown but not sold until their sizes are confirmed\n" +
  "   (scripts/lib/sizes-pending.js). Do not edit by hand. */\n" +
  "export const SIZES_PENDING = " + JSON.stringify(list) + ";\n");
writeFileSync(join(ROOT, "assets/data/sizes-pending.json"), JSON.stringify(list));
mkdirSync(join(ROOT, "reports"), { recursive: true });
writeFileSync(join(ROOT, "reports/calzedonia-intimissimi-2026-10-29.json"), JSON.stringify(report, null, 1));
