#!/usr/bin/env node
/* ============================================================
   search-engine.js — THE SITE'S SEARCH, FOR THE STANDALONE PAGE.

   WHY (2026-10-07, watch list). Every search typed on ariashop.pe is
   redirected to search.html, which carried its own twenty-line engine:
   exact-or-prefix words, every word required, no translation, no typo
   tolerance, no brands. "chort", "hudi", "swetshert", "youg la" and
   "victoria secret sales" were dead pages there while index.html's
   engine answered all of them -- the good engine was simply never run.

   So search.html now runs index.html's engine, lifted out by the same
   resolver the MCP connector uses (scripts/lib/mcp/page-slices.mjs):
   the pure search slice plus everything it calls, by name, from its
   own definition site. Nothing is re-implemented. This file is the
   output, committed so the static site can serve it.

   REGENERATE after any change to search in index.html:
     node scripts/build-search-engine.mjs
   scripts/test/search-watch-tests.mjs fails if this file has drifted.
   ============================================================ */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { sliceOfPage } from "./lib/mcp/page-slices.mjs";

export const ENGINE_EXPORTS = [
  "searchTokens", "catalogWordsOf", "catalogItemCategory", "rankCatalogMatches",
  "translateQuery", "soundCorrectQuery", "suggestSearchQuery", "buildSearchWordIndex",
  "itemSaleTier", "sizeCategoryFor", "isSoccer", "CATALOG_SEARCH_LIMIT",
];

export function buildSearchEngineSource() {
  const { source, pulledIn } = sliceOfPage({
    name: "search-engine",
    from: "const CATALOG_SEARCH_LIMIT = 200;",
    to: "/* END OF THE PURE SLICE",
    wants: ENGINE_EXPORTS,
    probe(api) {
      /* Call everything the page will call, on real input. */
      const pool = [
        { title: "Nike Club Fleece Pullover Hoodie", brand: "Nike", retailer: "dicks", price: 40, originalPrice: 60 },
        { title: "Men's Utility Shorts", brand: "", retailer: "walmart", price: 10 },
        { title: "Osiris D3 Skate Shoes", brand: "Osiris", retailer: "mainland", price: 90 },
      ];
      api.buildSearchWordIndex(pool);
      if (!pool._windex || !pool._windex.get("hoodie")) throw new Error("the index was not built");
      const t = api.translateQuery("zapatillas");
      if (!t || !t.query) throw new Error("translateQuery returned nothing");
      const fixed = api.soundCorrectQuery("hudi", pool._windex);
      if (fixed.query !== "hoodie") throw new Error("hudi did not correct to hoodie: " + fixed.query);
      const res = api.rankCatalogMatches(pool, "hoodie", { limit: 5, retailers: [] });
      if (!res.items.length) throw new Error("the ranker found nothing");
      api.suggestSearchQuery("hudi", pool._windex);
      api.suggestSearchQuery("xqzv", pool._windex);
      api.itemSaleTier(pool[0]);
      /* Every branch of the category rules, so nothing they reach only
         for some titles is left out of the file. */
      for (const [r, title] of [["dicks", pool[0].title], ["footlocker", "Nike Dunk Low - Women's"],
        ["walmart", "Wedgie Boot High-Rise Jeans"], ["target", "Plain Mug"], ["prosoccer", "Predator Elite FG"],
        ["macys", "Silk Scarf"], ["ulta", "Lipstick"], ["walmart", "Hanes Ankle Socks reinforced heel"]]){
        api.sizeCategoryFor(r, title);
        api.isSoccer({ title, retailer: r }, r);
        api.catalogItemCategory({ title, retailer: r, departments: ["toys"] });
        api.catalogItemCategory({ title, retailer: r, departments: [] });
      }
      for (const q of ["zapatillas nike", "aletas de buceo", "quillas", "victoria secret sales", "youg la",
        "chimpunes hasta 500 dolares", "polo hombre", "vs", "sephora", "nik", "short sleeve shirt"])
        api.rankCatalogMatches(pool, api.translateQuery(q).query, { limit: 5, retailers: [{ key: "sephora", label: "Sephora" }] });
    },
  });
  return [
    "/* GENERATED by scripts/build-search-engine.mjs from index.html — DO NOT EDIT.",
    "   index.html's own search (translation, typo and sound-alike correction,",
    "   brands, category intent, ranking), for the standalone search page.",
    `   Pulled in by name: ${pulledIn.join(", ")}. */`,
    "(function(){",
    source,
    `window.AriaSearch = { ${ENGINE_EXPORTS.join(", ")} };`,
    "})();",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = fileURLToPath(new URL("../search-engine.js", import.meta.url));
  const src = buildSearchEngineSource();
  writeFileSync(out, src);
  console.log(`search-engine.js: ${(src.length / 1024).toFixed(0)}KB`);
}
