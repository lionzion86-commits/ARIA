#!/usr/bin/env node
/* ============================================================
   tenniswarehouse-catalog.json FROM THE 2026-11-01 STORE SWEEP
   (#443 c.6565357697, c.6578887587).

   The delivery is on branch data/store-sweep-2026-11-01, file
   data/store-sweep-2026-11-01/tenniswarehouse-catalog.json (not on main:
   it is the pull, not the site; its report is tenniswarehouse-report.md
   beside it). Point --src at it:

     node scripts/build-tenniswarehouse-catalog.mjs --src <tenniswarehouse-catalog.json>

   The rules (aisles by what a product is, sizes, shown-not-sold,
   Spanish descriptions) are scripts/lib/tenniswarehouse.js. Spends
   nothing. Then the launch list, in order:
     node scripts/build-store-slices.mjs
     node scripts/build-ofertas-feed.mjs && node scripts/build-ofertas-slices.mjs && node scripts/build-ofertas-lite.mjs
     node scripts/build-search-index.mjs && node scripts/build-price-index.mjs
     node scripts/build-pdp-slices.mjs && node scripts/build-department-slices.mjs
     node scripts/build-brand-index.mjs && node scripts/build-home-shelves.mjs
     node scripts/build-home-category-pills.mjs && node scripts/build-store-rail-pills.mjs
     node scripts/build-store-doors.mjs && node scripts/build-search-destinations.mjs
   ============================================================ */
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { normalizeTennisWarehouse, TW_KEY, OUT_FILE } from "./lib/tenniswarehouse.js";
import { spanishFor } from "./lib/description-es.js";
import { sizesPendingKey } from "./lib/sizes-pending.js";
import { SIZES_PENDING } from "./lib/sizes-pending-data.js";
import { loadShippable } from "./build-store-slices.mjs";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const arg = (k) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : null; };
const SRC = arg("--src");
if (!SRC) { console.error("usage: node scripts/build-tenniswarehouse-catalog.mjs --src <store-sweep-2026-11-01/tenniswarehouse-catalog.json>"); process.exit(2); }

const delivered = JSON.parse(readFileSync(resolve(SRC), "utf8"));
const { catalog, moved, held } = normalizeTennisWarehouse(delivered, {
  spanishFor: (en) => spanishFor(TW_KEY, en),
  isShippableItem: loadShippable(ROOT),
});
const items = Object.values(catalog.retailers[TW_KEY].departments).flatMap((d) => d.items);
if (!items.length) { console.error("refusing to write an empty catalogue"); process.exit(1); }
writeFileSync(join(ROOT, OUT_FILE), JSON.stringify(catalog));

/* The shown-not-sold list the product page and the order door read:
   Tennis Warehouse's entries replaced, every other store's kept. */
const pending = new Set(SIZES_PENDING.filter((k) => !k.startsWith(TW_KEY + "::")));
for (const it of items) if (it.sizesPending) pending.add(sizesPendingKey(TW_KEY, it.name));
const list = [...pending].sort();
writeFileSync(join(ROOT, "scripts/lib/sizes-pending-data.js"),
  "/* GENERATED by scripts/build-pull-catalogs.mjs -- the items shown but not sold until their sizes are confirmed\n" +
  "   (scripts/lib/sizes-pending.js). Do not edit by hand. */\n" +
  "export const SIZES_PENDING = " + JSON.stringify(list) + ";\n");
writeFileSync(join(ROOT, "assets/data/sizes-pending.json"), JSON.stringify(list));

const byMove = {};
for (const m of moved) byMove[`${m.from} -> ${m.to}`] = (byMove[`${m.from} -> ${m.to}`] || 0) + 1;
console.log(JSON.stringify({
  wrote: OUT_FILE, products: items.length, delivered: delivered.declaredProductCount, held,
  onSale: items.filter((i) => i.onSale).length,
  withSizes: items.filter((i) => i.availableSizes.length).length,
  sizesPending: items.filter((i) => i.sizesPending).length,
  spanishDescriptions: items.filter((i) => i.description).length,
  byAisle: Object.fromEntries(Object.entries(catalog.retailers[TW_KEY].departments).map(([k, d]) => [k, d.items.length])),
  movedByProductType: byMove,
}, null, 1));
