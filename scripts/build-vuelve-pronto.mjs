#!/usr/bin/env node
/* ============================================================
   VUELVE PRONTO -- THE SOLD-OUT LIST (#443 c.6585537098, Danny).

   The site's one stock flag is the record's `so` (scripts/build-pdp-
   slices.mjs, from scripts/lib/variant-families.mjs: the store's own
   variant data lists that colourway or shade as not available now).
   This reads the product shards the build wrote (assets/pdp/p/*.json)
   and writes the list every surface checks:

     scripts/lib/vuelve-pronto-data.js   the keys, for the order
                                         endpoint, the restock-interest
                                         function and the Muse connector
     assets/data/vuelve-pronto.json      the same keys as FNV-1a hashes,
                                         for the pages (/vuelve-pronto.js):
                                         a few KB instead of the titles

   A key is "<retailer>::<title, lower case, spaces collapsed>" -- the
   sizes-pending key -- and is written only when EVERY record of that
   title at that store is sold out (two listings titled alike, one in
   stock, are not a sold-out card). A listing's own key adds "::v:<v>",
   and "*::<title>" stands for a title sold out at every store that
   carries it (a designer card links without its store). Products
   unavailable for another reason -- an off-sale store, a held used
   listing, pills and food (/off-sale.js) -- keep their own label and
   never enter the list.

   REGENERATE after build-pdp-slices.mjs:
     node scripts/build-vuelve-pronto.mjs
   scripts/test/vuelve-pronto-tests.mjs fails when the list is stale.
   ============================================================ */
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { isOffSaleItem } from "./lib/off-sale.js";
import "../vuelve-pronto.js";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const VP = globalThis.AriaVuelvePronto;

/** The keys the shards hold, sorted. */
export function soldOutKeys(shardDir = join(ROOT, "assets/pdp/p")) {
  const byTitle = new Map();   // retailer::title -> { n, so }
  const anyStore = new Map();  // *::title -> { n, so }
  const own = new Set();       // retailer::title::v:<v>
  const bump = (m, k, so) => { const e = m.get(k) || { n: 0, so: 0 }; e.n++; if (so) e.so++; m.set(k, e); };
  for (const f of readdirSync(shardDir).filter((x) => x.endsWith(".json")).sort()) {
    const d = JSON.parse(readFileSync(join(shardDir, f), "utf8"));
    for (const recs of Object.values(d)) {
      for (const r of Array.isArray(recs) ? recs : [recs]) {
        if (!r || typeof r !== "object" || !r.retailer || !r.name) continue;
        if (isOffSaleItem({ retailer: r.retailer, title: r.name })) continue;
        const so = r.so === 1;
        bump(byTitle, VP.key(r.retailer, r.name), so);
        bump(anyStore, VP.key("*", r.name), so);
        if (so && r.v) own.add(VP.key(r.retailer, r.name, r.v));
      }
    }
  }
  const out = new Set();
  for (const m of [byTitle, anyStore]) for (const [k, e] of m) if (e.so && e.so === e.n) out.add(k);
  /* A listing's own key only where its title's key does not already say it. */
  for (const k of own) if (!out.has(k.slice(0, k.lastIndexOf("::v:")))) out.add(k);
  return [...out].sort();
}

function main() {
  const keys = soldOutKeys();
  mkdirSync(join(ROOT, "assets/data"), { recursive: true });
  writeFileSync(join(ROOT, "scripts/lib/vuelve-pronto-data.js"),
    "/* GENERATED by scripts/build-vuelve-pronto.mjs -- the products the store lists as sold out\n"
    + "   (Vuelve pronto, scripts/lib/vuelve-pronto.js). Do not edit by hand. */\n"
    + "export const VUELVE_PRONTO = " + JSON.stringify(keys) + ";\n");
  const hashes = [...new Set(keys.map((k) => VP.hashKey(k)))].sort();
  writeFileSync(join(ROOT, "assets/data/vuelve-pronto.json"), JSON.stringify({ n: hashes.length, h: hashes.join(",") }) + "\n");
  const titles = keys.filter((k) => !k.startsWith("*::") && !k.includes("::v:")).length;
  console.log(`vuelve pronto: ${keys.length} keys (${titles} store titles), ${hashes.length} hashes`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
