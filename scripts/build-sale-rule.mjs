#!/usr/bin/env node
/* ============================================================
   sale-rule.js — IS THIS ON SALE, FOR THE STANDALONE PAGES.

   WHY (2026-10-13 audit, Part 2). Every page answered "is this on sale"
   its own way: tienda.html let a bare onSale flag in as "tier 1" (New
   Balance's Ofertas rail: 43 items, zero was-prices, no badge);
   departamento.html counted 1% off; none of them knew Shopify's
   compareAt (CCS, Surf Station, Mainland); only ofertas.html had the
   70% ceiling.

   So those pages now run index.html's one definition (saleDiscountPct,
   see rawItemOnSale's comment there), lifted out by name with
   scripts/lib/page-lift.mjs -- nothing re-implemented. This file is the
   output, committed so the static site can serve it.

   REGENERATE after any change to those declarations in index.html:
     node scripts/build-sale-rule.mjs
   scripts/test/sale-definition-tests.mjs fails if this file has drifted.
   ============================================================ */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { extractDeclarations, pageHtml } from "./lib/page-lift.mjs";

const ROOT = fileURLToPath(new URL("../", import.meta.url));

export const SALE_RULE_DECLARATIONS = [
  "MIN_DISCOUNT_PCT", "OFERTAS_MAX_DISCOUNT_PCT", "SALE_ORIGINAL_FIELDS",
  "saleNumber", "salePriceOf", "saleOriginalPrice", "saleDiscountPct", "isOnSaleItem",
  "OFERTAS_MIX_MAX_PRICE_USD", "isSaleItem",
];

export function buildSaleRuleSource() {
  const html = pageHtml(ROOT);
  return `/* GENERATED by scripts/build-sale-rule.mjs from index.html -- do not edit.
   Regenerate: node scripts/build-sale-rule.mjs */
(function (root) {
'use strict';
${extractDeclarations(html, SALE_RULE_DECLARATIONS)}
root.AriaSale = {
  discountPct: saleDiscountPct,
  isOnSale: isOnSaleItem,
  originalPrice: saleOriginalPrice,
  isMixDeal: isSaleItem,
  MIN_PCT: MIN_DISCOUNT_PCT,
  MAX_PCT: OFERTAS_MAX_DISCOUNT_PCT,
  MIX_MAX_PRICE_USD: OFERTAS_MIX_MAX_PRICE_USD
};
})(typeof window !== 'undefined' ? window : globalThis);
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const src = buildSaleRuleSource();
  writeFileSync(ROOT + "sale-rule.js", src);
  console.log(`sale-rule.js: ${(src.length / 1024).toFixed(1)}KB`);
}
