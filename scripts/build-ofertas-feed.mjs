#!/usr/bin/env node
/* ============================================================
   ofertas-feed.json — EVERY STORE'S MARKDOWNS, BY THE PAGE'S OWN RULES.

   WHY (2026-10-13, issue #386, "Ofertas department page"). The feed was
   regenerated by hand (last: 2026-10-04, #311) by running index.html's
   fileBackedDeals() in a browser, and that function skips the scraped
   stores (Walmart, Target, Old Navy, Foot Locker): their deals came only
   from the live sales-cache, which in production held 33 rows. So the
   Ofertas department listed Target at 0 while Target's own page showed
   4,245 markdowns.

   This script is that hand step, made repeatable: it serves the repo,
   opens index.html in headless Chromium, and runs
   fileBackedDeals({ allStores: true }) -- the page's own catalogue
   loading, normalizeLiveItem pricing and sale rule -- over every store.
   Rows are slimmed to what the Ofertas consumers read (no descriptions;
   the product page reads its catalogue). The lite head is built
   round-robin across stores, so the first paint is not four stores.

   RUN: node scripts/build-ofertas-feed.mjs
   (PLAYWRIGHT_CHROMIUM=<binary> to point at a browser.)
   scripts/test/assistant-turn-tests.mjs pins the per-store counts.
   ============================================================ */
import { chromium } from "playwright";
import { createServer } from "node:http";
import { readFile, writeFile, stat } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { extname, join, normalize } from "node:path";
import { liftDeclarations } from "./lib/page-lift.mjs";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const LITE_N = 800;
const TYPES = { ".html": "text/html", ".js": "text/javascript", ".mjs": "text/javascript", ".json": "application/json", ".css": "text/css" };

const server = createServer(async (req, res) => {
  const path = normalize(decodeURIComponent(new URL(req.url, "http://x").pathname)).replace(/^(\.\.[/\\])+/, "");
  try {
    const body = await readFile(join(ROOT, path === "/" ? "index.html" : path));
    res.writeHead(200, { "content-type": TYPES[extname(path)] || "application/octet-stream" });
    res.end(body);
  } catch { res.writeHead(404); res.end(); }
});
await new Promise((r) => server.listen(0, "127.0.0.1", r));
const base = `http://127.0.0.1:${server.address().port}`;

const exe = process.env.PLAYWRIGHT_CHROMIUM || undefined;
const browser = await chromium.launch(exe ? { executablePath: exe } : {});
const localOnly = (page) => page.route("**/*", (route) => (route.request().url().startsWith(base) && !/\.netlify\/functions/.test(route.request().url())
  ? route.continue() : route.fulfill({ status: 404, body: "" })));

/* 1. THE STORE'S OWN ITEMS, the way its page assembles them: tienda.html's
      file list per store (STORES), every department of every file, its
      name / price / photo rules (realImage) and its name+photo dedupe
      (loadStore). Lifted from tienda.html, not copied. */
const T = liftDeclarations(await readFile(join(ROOT, "tienda.html"), "utf8"), ["STORES", "realImage"]);
const fileCache = new Map();
async function readCatalogue(f){
  if (!fileCache.has(f)){
    let j = null;
    try { j = JSON.parse(await readFile(join(ROOT, f.replace(/^\//, "")), "utf8")); } catch (e) {}
    fileCache.set(f, j);
  }
  return fileCache.get(f);
}
const perStore = {};
for (const [storeKey, meta] of Object.entries(T.STORES)){
  const raws = [];
  for (const f of meta.files || []){
    const j = await readCatalogue(f);
    const bucket = j && j.retailers && j.retailers[storeKey];
    for (const [dk, entry] of Object.entries((bucket && bucket.departments) || {})){
      const arr = Array.isArray(entry) ? entry : entry && entry.items;
      for (const raw of arr || []) raws.push([dk, raw]);
    }
  }
  const seen = {}, list = [];
  for (const [dk, raw] of raws){
    if (!raw || typeof raw !== "object") continue;
    const name = raw.name || raw.title || raw.productName || "";
    if (!name || !(Number(raw.price) > 0)) continue;
    const img = T.realImage(raw);
    if (!img) continue;
    const key = name + "||" + img;
    if (seen[key]) continue;
    seen[key] = 1;
    list.push([dk, raw]);
  }
  perStore[storeKey] = list;
}

/* 2. PRICED AND JUDGED BY index.html: normalizeLiveItem (the card price,
      the badge) and its sale rule. */
const page = await browser.newPage();
await localOnly(page);
await page.goto(base + "/index.html", { waitUntil: "load", timeout: 120000 });
const items = [];
for (const [retailer, list] of Object.entries(perStore)){
  const deals = await page.evaluate(({ retailer, list }) => {
    const out = [];
    for (const [department, raw] of list){
      if (!rawItemOnSale(raw)) continue;
      const it = normalizeLiveItem(raw, { retailer, department });
      if (!it.title || !(Number(it.price) > 0) || !(it.onSale && Number(it.originalPrice) > Number(it.price))) continue;
      out.push({
        retailer, title: it.title, price: it.price, originalPrice: it.originalPrice,
        image: it.image || (it.images && it.images[0]) || null, images: (it.images || []).slice(0, 3),
        weightKg: it.weightKg, catalogWeightKg: it.catalogWeightKg, weightEstimated: it.weightEstimated,
        dutiableUsd: it.dutiableUsd, rating: it.rating, reviewCount: it.reviewCount,
        sizes: it.sizes, brand: it.brand, onSale: true,
      });
    }
    return out;
  }, { retailer, list });
  items.push(...deals);
}
await browser.close();
server.close();

const generatedAt = new Date().toISOString();
const counts = {};
for (const it of items) counts[it.retailer] = (counts[it.retailer] || 0) + 1;
await writeFile(join(ROOT, "ofertas-feed.json"), JSON.stringify({ generatedAt, count: items.length, counts, items }));
/* Round-robin by store, each store's biggest markdowns first. */
const byStore = new Map();
for (const it of items) (byStore.get(it.retailer) || byStore.set(it.retailer, []).get(it.retailer)).push(it);
for (const list of byStore.values()) list.sort((a, b) => (1 - a.price / a.originalPrice) < (1 - b.price / b.originalPrice) ? 1 : -1);
const lists = [...byStore.values()];
const lite = [];
for (let i = 0; lite.length < Math.min(LITE_N, items.length); i++)
  for (const l of lists) if (l[i] && lite.length < LITE_N) lite.push(l[i]);
await writeFile(join(ROOT, "ofertas-feed-lite.json"), JSON.stringify({ generatedAt, count: lite.length, lite: true, items: lite }));
const mb = ((await stat(join(ROOT, "ofertas-feed.json"))).size / 1048576).toFixed(2);
const kb = Math.round((await stat(join(ROOT, "ofertas-feed-lite.json"))).size / 1024);
console.log(`ofertas-feed.json: ${items.length} deals from ${byStore.size} stores, ${mb}MB; lite: ${lite.length}, ${kb}KB`);
