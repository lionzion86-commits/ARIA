#!/usr/bin/env node
/* ============================================================
   snipes-catalog.json + carolinaherrera-catalog.json FROM THE
   2026-10-27 PULLS (#443 c.6457579787).

   The raw datasets are on branch catalog-pulls-2026-10-27, folder
   catalog-pulls/2026-10-27/ (not on main: they are the pull, not the
   site). Point --src at a checkout of that folder:

     node scripts/build-pull-catalogs.mjs --src <dir with snipes.json and carolina-herrera.json>
     python3 apply-weight-estimates.py weight-estimates.json snipes-catalog.json --in-place
     python3 apply-weight-estimates.py weight-estimates.json carolinaherrera-catalog.json --in-place
     node scripts/apply-description-memory.mjs

   The rules are scripts/lib/store-pull-normalize.js. It writes the two
   catalogues and reports/store-pulls-2026-10-27.json, the counts the
   ingest report is written from (what was kept, what was left out and
   why, the release SKUs cut).
   ============================================================ */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { normalizeSnipes, normalizeCarolinaHerrera } from "./lib/store-pull-normalize.js";
import { sizesPendingKey } from "./lib/sizes-pending.js";
import { SIZES_PENDING } from "./lib/sizes-pending-data.js";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const arg = (k) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : null; };
const SRC = arg("--src");
if (!SRC) { console.error("usage: node scripts/build-pull-catalogs.mjs --src <catalog-pulls/2026-10-27 dir>"); process.exit(2); }

const STORES = [
  { key: "snipes", label: "SNIPES", raw: "snipes.json", norm: normalizeSnipes,
    source: "snipesusa.com product pages (JSON-LD) via Apify digital_influx/product-data, pulled 2026-10-27 (#443 c.6457579787)" },
  { key: "carolinaherrera", label: "Carolina Herrera", raw: "carolina-herrera.json", norm: normalizeCarolinaHerrera,
    source: "carolinaherrera.com US storefront product pages (JSON-LD) via Apify digital_influx/product-data, pulled 2026-10-27 (#443 c.6457579787)" },
];

const report = { generatedAt: new Date().toISOString(), stores: {} };
/* Other builders' entries (Calzedonia: scripts/build-calzedonia-
   intimissimi-catalogs.mjs) stay on the list; only these stores' are rebuilt. */
const pending = new Set(SIZES_PENDING.filter((k) => !STORES.some((s) => k.startsWith(s.key + "::"))));
for (const s of STORES) {
  const rows = JSON.parse(readFileSync(join(SRC, s.raw), "utf8"));
  const { departments, skipped, released } = s.norm(rows);
  const count = Object.values(departments).reduce((n, d) => n + d.items.length, 0);
  const out = { generatedAt: report.generatedAt, source: s.source, declaredProductCount: count,
    retailers: { [s.key]: { label: s.label, departments } } };
  writeFileSync(join(ROOT, s.key + "-catalog.json"), JSON.stringify(out));
  for (const d of Object.values(departments)) for (const it of d.items) if (it.sizesPending) pending.add(sizesPendingKey(s.key, it.name));
  report.stores[s.key] = {
    rawProducts: rows.filter((r) => r && r.type === "product").length, kept: count,
    byDepartment: Object.fromEntries(Object.entries(departments).map(([k, d]) => [k, d.items.length])),
    skipped, released: released || [],
    sizesPending: Object.values(departments).reduce((n, d) => n + d.items.filter((i) => i.sizesPending).length, 0),
    withDescription: Object.values(departments).reduce((n, d) => n + d.items.filter((i) => i.description).length, 0),
  };
  console.log(`${s.key}: ${count} kept of ${report.stores[s.key].rawProducts}`, report.stores[s.key].byDepartment, skipped, released ? `release SKUs cut: ${released.length}` : "");
}
/* The list the order endpoint reads (scripts/lib/sizes-pending.js). */
writeFileSync(join(ROOT, "scripts/lib/sizes-pending-data.js"),
  "/* GENERATED by scripts/build-pull-catalogs.mjs -- the items shown but not sold until their sizes are confirmed\n" +
  "   (scripts/lib/sizes-pending.js). Do not edit by hand. */\n" +
  "export const SIZES_PENDING = " + JSON.stringify([...pending].sort()) + ";\n");
/* ...and the copy the app's product sheet fetches for these stores only. */
mkdirSync(join(ROOT, "assets/data"), { recursive: true });
writeFileSync(join(ROOT, "assets/data/sizes-pending.json"), JSON.stringify([...pending].sort()));
mkdirSync(join(ROOT, "reports"), { recursive: true });
writeFileSync(join(ROOT, "reports/store-pulls-2026-10-27.json"), JSON.stringify(report, null, 1));
