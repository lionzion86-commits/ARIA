#!/usr/bin/env node
/* ============================================================
   product-type.js — WHAT KIND OF PRODUCT IS THIS, FOR THE STANDALONE PAGES.

   WHY (2026-10-13 classification audit). tienda.html and marca.html --
   the store and brand pages every shopper lands on -- carried their own
   copy of index.html's product-type tiles: jewelry before shoes, the
   name only, the type field ignored. New Balance's store page was one
   "Ropa (746)" rail of its 754 products, and "Jordan 6 Rings" was Joyas.

   So those pages now run index.html's classifier (latinoProductTypeOfItem
   and the footwear brain it calls), lifted out by name with
   scripts/lib/page-lift.mjs -- nothing re-implemented. This file is the
   output, committed so the static site can serve it.

   REGENERATE after any change to those declarations in index.html:
     node scripts/build-product-type.mjs
   scripts/test/classification-tests.mjs fails if this file has drifted.
   ============================================================ */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { extractDeclarations, pageHtml } from "./lib/page-lift.mjs";

const ROOT = fileURLToPath(new URL("../", import.meta.url));

/* What is this product (#443 re-route audit): the head-noun families
   latinoProductTypeOfItem reads first. scripts/census-classification.mjs
   lifts the same list. */
export const ITEM_FAMILY_DECLARATIONS = [
  "ITEM_FAMILY_LABELS", "ITEM_FAMILY_DEPT", "ITEM_NAME_MASKS", "itemNounMinLength", "ITEM_FAMILY_NOUNS", "ITEM_WEAK_NOUNS", "TOY_BRAND_RX",
  "STRONG_TOY_RX", "STRONG_FRAGRANCE_RX", "STRONG_DOLL_RX", "TOY_OVER", "ITEM_FAMILY_TYPES", "SEGMENT_CUT_RX",
  "itemHeadFamily", "itemFamilyOfName", "itemFamilyOfType", "ITEM_FAMILY_RETAILERS", "ITEM_FAMILY_GENERIC",
];
export const PRODUCT_TYPE_DECLARATIONS = [
  "FOOTWEAR_TYPE", "FOOTWEAR_TITLE", "CLEAT_HIKER_RX", "NOT_FOOTWEAR", "FOOTWEAR_RETAILERS",
  "OXFORD_CLOTH_RX", "FOOTWEAR_NOUN_NOT_OXFORD", "isFootwearType", "isFootwearTitle", "isFootwear",
  "SHOE_MODEL_RX", "NB_MODEL_RX", "SHOE_MODEL_APPAREL_VETO", "isShoeModel",
  "CATCHALL_TYPE_RX", "isCatchallType", "BUCKET_TYPE_RX", "NOT_FOOTWEAR_RX", "isFootwearLoose",
  ...ITEM_FAMILY_DECLARATIONS,
  "LATINO_PRODUCT_TYPES", "latinoProductTypeOfItem",
];

export function buildProductTypeSource() {
  const html = pageHtml(ROOT);
  return `/* GENERATED by scripts/build-product-type.mjs from index.html -- do not edit.
   Regenerate: node scripts/build-product-type.mjs */
(function (root) {
'use strict';
${extractDeclarations(html, PRODUCT_TYPE_DECLARATIONS)}
root.AriaProductType = {
  classify: latinoProductTypeOfItem,
  isFootwear: isFootwear,
  isFootwearLoose: isFootwearLoose,
  familyOfName: itemFamilyOfName,
  familyOfType: itemFamilyOfType,
  FAMILY_DEPT: ITEM_FAMILY_DEPT,
  TYPES: LATINO_PRODUCT_TYPES.map(function (t) { return { key: t.key, label: t.label }; })
};
})(typeof window !== 'undefined' ? window : globalThis);
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const src = buildProductTypeSource();
  writeFileSync(ROOT + "product-type.js", src);
  console.log(`product-type.js: ${Math.round(src.length / 1024)}KB`);
}
