#!/usr/bin/env node
/* ============================================================
   BUNDLE ARIA'S BRAIN FOR THE VOICE WORKER.

   src/brain.entry.mjs names the repo modules the owned voice shares
   with the Realtime session and the chat assistant; this writes them
   as one self-contained file, src/brain.generated.mjs, so the worker
   image (voice-agent/Dockerfile) needs nothing outside voice-agent/.

   Run after any change to the prompt, the voice rules or the tools:

     node voice-agent/scripts/build-brain.mjs

   The owned-voice tests rebuild it in memory and fail if the committed
   file differs, so a stale brain cannot ship.
   ============================================================ */
import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const HERE = fileURLToPath(new URL("../", import.meta.url));
export const OUT = HERE + "src/brain.generated.mjs";

const BANNER = "/* GENERATED by voice-agent/scripts/build-brain.mjs from src/brain.entry.mjs -- do not edit. */";

export async function bundleBrain() {
  const r = await build({
    entryPoints: [HERE + "src/brain.entry.mjs"],
    bundle: true,
    format: "esm",
    platform: "node",
    target: "node20",
    write: false,
    legalComments: "none",
    banner: { js: BANNER },
  });
  return r.outputFiles[0].text;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await bundleBrain();
  writeFileSync(OUT, text);
  console.log(`src/brain.generated.mjs: ${(text.length / 1024).toFixed(1)}KB`);
}
